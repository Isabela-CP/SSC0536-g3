export function labelFor(path) {
  const key = path.split('.').at(-1)
  if (labels[key]) return labels[key]
  const text = key
    .split('_')
    .map((word) => words[word] || word)
    .join(' ')
  return text.charAt(0).toLocaleUpperCase('pt-BR') + text.slice(1)
}
